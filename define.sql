
    create table abbonamento_attivita (
        abbonamento_id integer not null,
        attivita_id integer not null
    );

    create table abbonamento_socio (
        data_iscrizione date not null,
        durata_validita integer not null,
        id integer generated by default as identity,
        id_socio integer,
        primary key (id)
    );

    create table attivita (
        id integer generated by default as identity,
        prezzo_attivita bigint not null,
        descrizione_attivita varchar(100) not null,
        primary key (id)
    );

    create table certificato_medico (
        data_certificato date,
        id integer generated by default as identity,
        tipo_certificato boolean,
        primary key (id)
    );

    create table messaggi_sistema (
        lang varchar(4) not null,
        code varchar(20) not null,
        messagio varchar(255),
        primary key (lang, code)
    );

    create table pagamento_ricevute (
        data_pagamento date not null,
        id integer generated by default as identity,
        id_abbonamento integer,
        id_attivita integer,
        prezzo_pagatp bigint not null,
        primary key (id)
    );

    create table socio (
        certificato_id integer unique,
        id integer generated by default as identity,
        codice_fiscale varchar(16) not null unique,
        cognome varchar(100) not null,
        nome varchar(100) not null,
        email varchar(255),
        primary key (id)
    );

    create table utente (
        role smallint check ((role between 0 and 2)),
        email varchar(255),
        pwd varchar(255),
        user_name varchar(255) not null,
        primary key (user_name)
    );

